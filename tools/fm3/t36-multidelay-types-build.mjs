// Build the T36 Multi Delay Type check pack (0.3.56 multidelayTypes). Offline; writes one measurement preset, never device I/O.
// The preset is made only through the public generator input multidelayTypes: channel A Pealing Bells (+ Mix 30 % via
// controls on top of the template), B Dub Echo, C Mono Diffuser, D Aurora Delay. Scenes 1..4 engage the Multi Delay on
// channels A..D. Questions: does the FM3 hold all 484 generated words after loading (fn=0x1F read-back, word for word),
// does FM3-Edit show the four Type names, and do the channels sound like those Types?
// FM3_SHOT_LOAD.py --load sends the preset to the edit buffer (7F 00) and reads the Multi Delay block back. Nothing is
// stored or set.
// Usage: node tools/fm3/t36-multidelay-types-build.mjs OUT_DIR
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import * as R from './fm3-read-requests.mjs';
const E='../../plugins/fm3-sound-architect-2/skills/fm3-sound-architect-2/engine/skills/instructions/';
const imp=p=>import(new URL(E+p,import.meta.url));
const {composeSound}=await imp('scripts/fm3-sound.mjs');
const {scanRecords}=await imp('scripts/fm3-layout.mjs');
const {inspectStructure}=await imp('scripts/drive-collector/fm3-prototype.mjs');
const {parsePresetDump}=await imp('scripts/fm3-codec.mjs');
const {multidelayType}=await imp('scripts/fm3-multidelay-types.mjs');
const sha=b=>createHash('sha256').update(b).digest('hex'),hex=a=>Buffer.from(a).toString('hex');
const [out]=process.argv.slice(2);assert.ok(out,'Usage: t36-multidelay-types-build.mjs OUT_DIR');
const read=p=>fs.readFileSync(new URL(E+p,import.meta.url));
const COLLECT=new URL(E+'scripts/cpu-sweep-collector/',import.meta.url);
const NEWLOOK=read('examples/JB_RHYTHM_LEVEL_MINUS3_NewLook.syx');
const WORDS=121,EID=74,NAME='T36 MD TYPES';
const TYPES=[['A','Pealing Bells'],['B','Dub Echo'],['C','Mono Diffuser'],['D','Aurora Delay']];
const spec={composer:{schemaVersion:1,firmware:13,baseProfile:'jb-composer',name:NAME,compressorChannels:[{channel:'A',type:'Optical Compressor'}],
    scenes:TYPES.map(([c,t],i)=>({scene:i+1,name:c+' '+t}))},
  insert:['multidelay'],recordOrder:'append',selectedScene:1,layout:{row2:['compressor','drive','amp','cab'],row3:['delay','multidelay','reverb']},
  multidelayTypes:TYPES.map(([channel,type])=>({channel,type})),
  controls:[{block:'multidelay',channel:'A',param:'MULTITAP_MIX',value:30}],
  blockScenes:{multidelay:TYPES.map(([channel],i)=>({scene:i+1,channel,bypass:false}))}};
const r=composeSound(NEWLOOK,spec),syx=Buffer.from(r.syx);
assert.deepEqual([...parsePresetDump(syx,0,17).headerPayload],[0x7f,0,0,0x40,0],'edit-buffer header');
const body=Buffer.from(inspectStructure(syx).raw.body),rec=scanRecords(body,{requireAmpCab:false}).records.find(x=>x.eid===EID);
assert.ok(rec&&rec.words===WORDS&&rec.channels===4,'Multi Delay record');
const expected=[...Array(4*WORDS).keys()].map(i=>body.readUInt16LE(rec.start+2*i));
const mixW=r.report.controls.find(c=>c.block==='multidelay'&&c.name==='MULTITAP_MIX');assert.ok(mixW,'Mix write');
// Channels B..D are exactly the T35 images; A is the image plus the Mix word.
TYPES.forEach(([c,t],k)=>{const img=multidelayType(t).words,got=expected.slice(k*WORDS,(k+1)*WORDS);
  const d=img.map((w,i)=>w!==got[i]?i:-1).filter(i=>i>=0);assert.deepEqual(d,c==='A'?[mixW.pid]:[],c+' '+t);});
const item={id:'MDT',file:'MDT.syx',sha256:sha(syx),name:NAME,
  question:'Holds the FM3 all 484 Multi Delay words generated by multidelayTypes? FM3-Edit Type per channel A..D = Pealing Bells / Dub Echo / Mono Diffuser / Aurora Delay? Scenes 1..4 sound like those Types?',
  types:TYPES.map(([channel,type])=>({channel,type,index:multidelayType(type).index})),
  blocks:[{family:'multidelay',effectId:EID,words:WORDS,channels:4,request:hex(R.bulkReadPoll(EID)),expected,
    writes:[{param:'MULTITAP_MIX',channel:'A',pid:mixW.pid,raw:mixW.raw,value:30}]}]};
const dir=path.join(out,'FM3_T36_MDTYPES');fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(dir,item.file),syx);
for(const f of ['FM3_SHOT_LOAD.py','FM3_CPU_SWEEP.py','FM3_READ_PROBE.py'])fs.copyFileSync(new URL(f,COLLECT),path.join(dir,f));
const manifest={kind:'fm3-shot-check',version:1,date:'2026-11-07',test:'T36',title:'Multi Delay Type mallina (multidelayTypes 0.3.56): laadimine, lugemine, kuulamine',experimental:false,observeOnly:true,
  generator:r.report.generator,
  method:'FM3_SHOT_LOAD.py --load sends the generated preset to the edit buffer (7F 00) and reads the Multi Delay record (74) with fn=0x1F (read-only), word for word against the generated file; the user checks the FM3-Edit Type names without saving and listens to scenes 1..4. Nothing is stored or set.',
  items:[item]};
fs.writeFileSync(path.join(dir,'manifest.json'),JSON.stringify(manifest,null,1)+'\n');
const L=['FM3 katse T36: Multi Delay Type mallina (ainult laadimine ja lugemine)','='.repeat(64),
 'Skriptid EI salvesta ega sea midagi. STORE-i pole vaja. FM3-Editis EI vajutata Save.',
 'Ampero A-nuppu ära kasuta, B-nuppu ainult lühidalt (kui üldse).','',
 'Preset "T36 MD TYPES": Multi Delay kanalid A Pealing Bells (Mix 30 %), B Dub Echo, C Mono Diffuser, D Aurora Delay.',
 'Stseenid 1–4 lülitavad Multi Delay kanalile A–D (plokk sees).','',
 '1. FM3-Edit ja Fractal-Bot kinni, siis Terminalis:',
 '   cd ~/Downloads/FM3_REA_DEVELOPMENT/FM3_T36_MDTYPES && python3 FM3_SHOT_LOAD.py --self-test',
 '   python3 FM3_SHOT_LOAD.py --load --pack . --session ../FM3_T36_SESSION',
 '   Oodatud: "multidelay KLAPIB".',
 '2. Ava FM3-Edit (ära vajuta Save): Multi Delay plokk, vaata kanalitel A–D välja "Type".',
 '   Oodatud: A Pealing Bells, B Dub Echo, C Mono Diffuser, D Aurora Delay. A kanalil Mix 30 %.',
 '3. Mängi stseenid 1–4 läbi ja kuula, kas kõlab nagu need Type\'id.',
 '4. Kirjuta Claude\'ile, mida nägid ja kuulsid, ning "valmis".',''];
fs.writeFileSync(path.join(dir,'LOE_MIND.txt'),L.join('\n'));
console.log(JSON.stringify({manifest:sha(fs.readFileSync(path.join(dir,'manifest.json'))),sha256:item.sha256,generator:r.report.generator,cpu:r.report.cpu?.total??r.report.cpu}));
